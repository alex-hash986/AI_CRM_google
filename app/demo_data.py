def lead_values(name: str, scenario: tuple[str, int, str, int, str]) -> list[Cell]:
    source, budget, activity, _, _ = scenario
    lead_id = uuid4().hex
    return [lead_id, utc_now(), name, f"demo-{lead_id[:8]}@example.com", source, budget, activity, "Новый"]


def simulated_lead() -> list[Cell]:
    return lead_values(choice(NAMES), choice(SCENARIOS))


def demo_rows(threshold: int) -> list[list[Cell]]:
    rows = []
    for index, (name, scenario) in enumerate(zip(NAMES, SCENARIOS, strict=True)):
        values = lead_values(name, scenario)
        if index < 21:
            _, _, _, score, action = scenario
            if index in (0, 4, 7):
                values[7] = "В работе"
            if index == 3:
                values[7] = "Отказ"
            risk = "Уточнить бюджет и сроки внедрения" if score < 65 else "Рисков не выявлено"
            values += [
                score, classify(score, threshold), f"{action}.",
                f"{name.split()[0]}, добрый день! Можем обсудить ваш запрос. "
                f"Предлагаю начать с короткого созвона. Вам удобно на этой неделе?",
                risk, score >= threshold, utc_now() if values[7] != "Новый" else "", utc_now(),
            ]
        rows.append(values)
    return rows
